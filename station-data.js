function findRoute(dep, arr) {
  for (const route of ROUTES) {
    const depIdx = route.stations.indexOf(dep);
    const arrIdx = route.stations.indexOf(arr);
    if (depIdx !== -1 && arrIdx !== -1) {
      return { route, depIdx, arrIdx };
    }
  }
  return null;
}

