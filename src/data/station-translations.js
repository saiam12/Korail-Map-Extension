  const INITIALS = ["g", "kk", "n", "d", "tt", "r", "m", "b", "pp", "s", "ss", "", "j", "jj", "ch", "k", "t", "p", "h"];
  const MEDIALS = ["a", "ae", "ya", "yae", "eo", "e", "yeo", "ye", "o", "wa", "wae", "oe", "yo", "u", "wo", "we", "wi", "yu", "eu", "ui", "i"];
  const FINALS = ["", "k", "k", "ks", "n", "nj", "nh", "t", "l", "lk", "lm", "lb", "ls", "lt", "lp", "lh", "m", "p", "ps", "t", "t", "ng", "t", "t", "k", "t", "p", "t"];

  function romanizeSyllable(char) {
    const code = char.charCodeAt(0);
    if (code < 0xac00 || code > 0xd7a3) return char;
    const offset = code - 0xac00;
    const initial = Math.floor(offset / 588);
    const medial = Math.floor((offset % 588) / 28);
    const final = offset % 28;
    return INITIALS[initial] + MEDIALS[medial] + FINALS[final];
  }

  function titleCase(value) {
    return value.replace(/[a-z]+/g, (part) => part.charAt(0).toUpperCase() + part.slice(1));
  }

  function romanizeKoreanStationName(name) {
    return titleCase(
      String(name || "")
        .replace(/[가-힣]/g, romanizeSyllable)
        .replace(/\(.*?\)/g, "")
        .replace(/\s+/g, " ")
        .trim()
    );
  }

  function getStationTranslationMap(locale, stations) {
    const base = { ...(STATION_TRANSLATIONS[locale] || {}) };
    if (stations) {
      Object.keys(stations).forEach((name) => {
        if (!base[name]) base[name] = STATION_TRANSLATIONS.en[name] || romanizeKoreanStationName(name);
      });
    }
    return base;
  }

